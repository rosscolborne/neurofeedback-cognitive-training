#!/usr/bin/env node
// Checks an App.app that xcodebuild produced (NFCT-30, NFCT-31), so the
// settings are proven on the built product rather than only in the project:
//
//   node scripts/ios/check-built-app.mjs <path/to/App.app> <Debug|Release>
//
// Capacitor makes the web view inspectable, and forwards console output, only
// when the built Info.plist has CAPACITOR_DEBUG = "true". Debug builds must
// have it; Release builds, and therefore archives, must not. A Release build
// must also carry a production web bundle and a safe Capacitor config.
// Needs macOS (plutil).
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { checkCapacitorConfig, checkWebBundle } from '../verify-ios-release.mjs';

const [app, configuration] = process.argv.slice(2);
if (!app || !['Debug', 'Release'].includes(configuration) || !existsSync(join(app, 'Info.plist'))) {
  console.error('Usage: check-built-app.mjs <path/to/App.app> <Debug|Release>');
  process.exit(2);
}

const info = JSON.parse(execFileSync('plutil', ['-convert', 'json', '-o', '-', join(app, 'Info.plist')], { encoding: 'utf8' }));
// Generated by `cap sync` from capacitor.config.ts.
const syncedPath = join(app, 'capacitor.config.json');
const synced = existsSync(syncedPath) ? JSON.parse(readFileSync(syncedPath, 'utf8')) : null;
const problems = [];
const expect = (ok, message) => { if (!ok) problems.push(message); };

expect(synced !== null && info.CFBundleIdentifier === synced.appId, `CFBundleIdentifier is ${info.CFBundleIdentifier}, not the Capacitor appId ${synced?.appId}.`);
expect(JSON.stringify(info.UIDeviceFamily) === '[1]', `UIDeviceFamily is ${JSON.stringify(info.UIDeviceFamily)}; the native app is iPhone-only.`);
expect(info.MinimumOSVersion === '16.4', `MinimumOSVersion is ${info.MinimumOSVersion}, not 16.4.`);
expect(!('NSAppTransportSecurity' in info), 'The built Info.plist has an App Transport Security exception.');
if (configuration === 'Debug') {
  expect(info.CAPACITOR_DEBUG === 'true', `Debug CAPACITOR_DEBUG is ${JSON.stringify(info.CAPACITOR_DEBUG)}; Debug builds should be inspectable.`);
} else {
  expect(info.CAPACITOR_DEBUG === '', `Release CAPACITOR_DEBUG is ${JSON.stringify(info.CAPACITOR_DEBUG)}; Release must not be inspectable.`);
  const publicDir = join(app, 'public');
  const scripts = readdirSync(publicDir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.js'))
    .map((entry) => join(entry.parentPath, entry.name));
  problems.push(...checkWebBundle({
    indexHtml: existsSync(join(publicDir, 'index.html')) ? readFileSync(join(publicDir, 'index.html'), 'utf8') : null,
    scripts: scripts.map((path) => ({ path: relative(app, path), text: readFileSync(path, 'utf8') })),
  }));
  problems.push(...checkCapacitorConfig(synced));
}

if (problems.length > 0) {
  console.error(`Built ${configuration} app check failed (${app}):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log(`Built ${configuration} app check passed: ${info.CFBundleIdentifier}, iPhone-only, iOS ${info.MinimumOSVersion}+, `
  + (configuration === 'Debug' ? 'inspectable web view.' : 'not inspectable, production web bundle.'));
